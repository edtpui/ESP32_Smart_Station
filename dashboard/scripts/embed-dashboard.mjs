// Gzips dist/index.html into a C header that the firmware serves from flash.
// Run with: npm run build:esp32
import { createHash } from "node:crypto"
import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { gzipSync } from "node:zlib"

const html = readFileSync(fileURLToPath(new URL("../dist/index.html", import.meta.url)))
const target = fileURLToPath(new URL("../../ESP32_Smart_Station/web_dashboard.h", import.meta.url))

const gzipped = gzipSync(html, { level: 9 })
const etag = createHash("sha1").update(html).digest("hex").slice(0, 16)

const lines = []
for (let i = 0; i < gzipped.length; i += 24) {
  lines.push("  " + [...gzipped.subarray(i, i + 24)].map((byte) => `0x${byte.toString(16).padStart(2, "0")}`).join(","))
}

writeFileSync(
  target,
  `#pragma once
// Generated by dashboard/scripts/embed-dashboard.mjs. Do not edit: change the
// dashboard/ source and run "npm run build:esp32" instead.
#include <Arduino.h>

const char DASHBOARD_ETAG[] = "\\"${etag}\\"";
const size_t DASHBOARD_HTML_GZ_LEN = ${gzipped.length};
const uint8_t DASHBOARD_HTML_GZ[] PROGMEM = {
${lines.join(",\n")}
};
`
)

console.log(`web_dashboard.h: ${html.length} bytes of HTML, ${gzipped.length} bytes gzipped`)
